int main(void) {
    printf("[test_jpegtran] Starting lossless JPEG transform tests...\n");

    size_t mem_size = 8 * 1024 * 1024;
    void *raw = malloc(mem_size);
    assert(raw != NULL);
    proven_arena_t arena = proven_arena_create((proven_mem_mut_t){ .ptr = raw, .size = mem_size });

    /* Test 1: the size and MCU geometry are read without decoding. */
    {
        int32_t w = 0, h = 0, mw = 0, mh = 0;
        assert(rubraview_jpegtran_probe(JPEG_EXACT, sizeof(JPEG_EXACT), &w, &h, &mw, &mh));
        assert(w == 64 && h == 48);
        assert(mw == 16 && mh == 16); /* 4:2:0 */

        assert(rubraview_jpegtran_probe(JPEG_RAGGED, sizeof(JPEG_RAGGED), &w, &h, &mw, &mh));
        assert(w == 61 && h == 45);
    }
    printf("  [PASS] Size and MCU geometry are read without decoding\n");

    /* Test 2: which transforms can be exact, and which cannot. This is
       the arithmetic the caller needs before it promises anything. */
    {
        assert(rubraview_jpegtran_is_exact(RUBRAVIEW_JPEGTRAN_ROT_90, 64, 48, 16, 16));
        assert(!rubraview_jpegtran_is_exact(RUBRAVIEW_JPEGTRAN_ROT_90, 61, 45, 16, 16));

        /* A horizontal flip mirrors columns, so only the width matters. */
        assert(rubraview_jpegtran_is_exact(RUBRAVIEW_JPEGTRAN_FLIP_H, 64, 45, 16, 16));
        assert(!rubraview_jpegtran_is_exact(RUBRAVIEW_JPEGTRAN_FLIP_H, 61, 48, 16, 16));
        assert(rubraview_jpegtran_is_exact(RUBRAVIEW_JPEGTRAN_FLIP_V, 61, 48, 16, 16));

        /* Doing nothing is always exact. */
        assert(rubraview_jpegtran_is_exact(RUBRAVIEW_JPEGTRAN_NONE, 61, 45, 16, 16));
    }
    printf("  [PASS] Exactness follows the MCU grid, per transform\n");

    /* Test 3: a 90-degree rotation produces a valid JPEG with the
       dimensions swapped — and it is a JPEG, not a pile of bytes. */
    {
        rubraview_jpegtran_result_t r = rubraview_jpegtran_apply(
            &arena, JPEG_EXACT, sizeof(JPEG_EXACT), RUBRAVIEW_JPEGTRAN_ROT_90,
            RUBRAVIEW_JPEGTRAN_TRIM, false);
        assert(r.err == RUBRAVIEW_JPEGTRAN_OK);
        assert(r.was_exact);
        assert(r.data.len > 100);
        assert((uint8_t)r.data.ptr[0] == 0xFF && (uint8_t)r.data.ptr[1] == 0xD8);

        int32_t w = 0, h = 0;
        assert(rubraview_jpegtran_probe((const uint8_t*)r.data.ptr, r.data.len, &w, &h, NULL, NULL));
        assert(w == 48 && h == 64);
    }
    printf("  [PASS] A 90-degree rotation swaps the dimensions and stays a JPEG\n");

    /* Test 4: the claim that makes this worth vendoring a library for.
       Rotating four times must return the original *coefficients*. If
       anything were being decoded and re-encoded, four quantisation
       passes would have left their mark and the bytes would differ. */
    {
        u8str_t current = { .ptr = (const char*)JPEG_EXACT, .len = sizeof(JPEG_EXACT) };
        for (int i = 0; i < 4; ++i) {
            rubraview_jpegtran_result_t r = rubraview_jpegtran_apply(
                &arena, (const uint8_t*)current.ptr, current.len,
                RUBRAVIEW_JPEGTRAN_ROT_90, RUBRAVIEW_JPEGTRAN_TRIM, false);
            assert(r.err == RUBRAVIEW_JPEGTRAN_OK);
            current = r.data;
        }

        int32_t w = 0, h = 0;
        assert(rubraview_jpegtran_probe((const uint8_t*)current.ptr, current.len, &w, &h, NULL, NULL));
        assert(w == 64 && h == 48);

        /* Compare the entropy-coded data, not the whole file: the
           headers may be written slightly differently, but the
           coefficients themselves must be identical. Finding the start
           of scan in both and comparing from there is enough. */
        const uint8_t *a = JPEG_EXACT; size_t alen = sizeof(JPEG_EXACT);
        const uint8_t *b = (const uint8_t*)current.ptr; size_t blen = current.len;
        size_t ai = 0, bi = 0;
        while (ai + 1 < alen && !(a[ai] == 0xFF && a[ai + 1] == 0xDA)) ai++;
        while (bi + 1 < blen && !(b[bi] == 0xFF && b[bi + 1] == 0xDA)) bi++;
        assert(ai + 1 < alen && bi + 1 < blen);
        assert(alen - ai == blen - bi);
        assert(memcmp(a + ai, b + bi, alen - ai) == 0);
    }
    printf("  [PASS] Four 90-degree rotations return the original coefficients exactly\n");

    /* Test 5: an image that does not fit the MCU grid. Each of the
       three policies does what it says. */
    {
        /* Refuse: the caller would rather re-encode than be subtly wrong. */
        rubraview_jpegtran_result_t refused = rubraview_jpegtran_apply(
            &arena, JPEG_RAGGED, sizeof(JPEG_RAGGED), RUBRAVIEW_JPEGTRAN_ROT_90,
            RUBRAVIEW_JPEGTRAN_REFUSE_IF_INEXACT, false);
        assert(refused.err == RUBRAVIEW_JPEGTRAN_ERR_INEXACT);
        assert(refused.data.len == 0);

        /* Trim: exact, and a few pixels smaller. */
        rubraview_jpegtran_result_t trimmed = rubraview_jpegtran_apply(
            &arena, JPEG_RAGGED, sizeof(JPEG_RAGGED), RUBRAVIEW_JPEGTRAN_ROT_90,
            RUBRAVIEW_JPEGTRAN_TRIM, false);
        assert(trimmed.err == RUBRAVIEW_JPEGTRAN_OK);
        assert(!trimmed.was_exact); /* it had to give up the edge */
        int32_t tw = 0, th = 0;
        assert(rubraview_jpegtran_probe((const uint8_t*)trimmed.data.ptr, trimmed.data.len, &tw, &th, NULL, NULL));
        assert(tw <= 45 && th <= 61);

        /* Keep: every pixel survives, the edge just was not rotated. */
        rubraview_jpegtran_result_t kept = rubraview_jpegtran_apply(
            &arena, JPEG_RAGGED, sizeof(JPEG_RAGGED), RUBRAVIEW_JPEGTRAN_ROT_90,
            RUBRAVIEW_JPEGTRAN_KEEP_EDGE, false);
        assert(kept.err == RUBRAVIEW_JPEGTRAN_OK);
        int32_t kw = 0, kh = 0;
        assert(rubraview_jpegtran_probe((const uint8_t*)kept.data.ptr, kept.data.len, &kw, &kh, NULL, NULL));
        assert(kw == 45 && kh == 61);
    }
    printf("  [PASS] A ragged image trims, keeps or refuses as the caller chose\n");

    /* Test 6: every operation runs and produces a readable JPEG. */
    {
        const rubraview_jpegtran_op_t OPS[] = {
            RUBRAVIEW_JPEGTRAN_ROT_180, RUBRAVIEW_JPEGTRAN_ROT_270,
            RUBRAVIEW_JPEGTRAN_FLIP_H, RUBRAVIEW_JPEGTRAN_FLIP_V,
            RUBRAVIEW_JPEGTRAN_TRANSPOSE, RUBRAVIEW_JPEGTRAN_TRANSVERSE,
        };
        for (size_t i = 0; i < sizeof(OPS) / sizeof(OPS[0]); ++i) {
            rubraview_jpegtran_result_t r = rubraview_jpegtran_apply(
                &arena, JPEG_EXACT, sizeof(JPEG_EXACT), OPS[i], RUBRAVIEW_JPEGTRAN_TRIM, false);
            assert(r.err == RUBRAVIEW_JPEGTRAN_OK);
            int32_t w = 0, h = 0;
            assert(rubraview_jpegtran_probe((const uint8_t*)r.data.ptr, r.data.len, &w, &h, NULL, NULL));
            assert(w > 0 && h > 0);
        }
    }
    printf("  [PASS] Every transform produces a readable JPEG\n");

    /* Test 7: §3.10's zero-touch strip. The metadata goes, the
       coefficients stay, and the file gets smaller. */
    {
        rubraview_jpegtran_result_t stripped = rubraview_jpegtran_strip_metadata(
            &arena, JPEG_EXACT, sizeof(JPEG_EXACT));
        assert(stripped.err == RUBRAVIEW_JPEGTRAN_OK);
        assert(stripped.data.len > 100);

        int32_t w = 0, h = 0;
        assert(rubraview_jpegtran_probe((const uint8_t*)stripped.data.ptr, stripped.data.len, &w, &h, NULL, NULL));
        assert(w == 64 && h == 48);  /* nothing moved */

        /* No APP1 segment remains. */
        const uint8_t *b = (const uint8_t*)stripped.data.ptr;
        for (size_t i = 0; i + 1 < stripped.data.len; ++i) {
            if (b[i] == 0xFF && b[i + 1] == 0xDA) break;   /* stop at the scan */
            assert(!(b[i] == 0xFF && b[i + 1] == 0xE1));   /* APP1 = EXIF/XMP */
        }
    }
    printf("  [PASS] The metadata strip removes APP1 and moves no coefficient\n");

    /* Test 8: rubbish in gives an error out, not a crash. libjpeg
       reports errors by longjmp, which is exactly the thing that would
       take a viewer down if it were not caught. */
    {
        const uint8_t not_jpeg[64] = { 'P', 'N', 'G', 0 };
        rubraview_jpegtran_result_t r = rubraview_jpegtran_apply(
            &arena, not_jpeg, sizeof(not_jpeg), RUBRAVIEW_JPEGTRAN_ROT_90,
            RUBRAVIEW_JPEGTRAN_TRIM, false);
        assert(r.err == RUBRAVIEW_JPEGTRAN_ERR_NOT_A_JPEG);

        /* Truncated in the middle of the scan. */
        rubraview_jpegtran_result_t cut = rubraview_jpegtran_apply(
            &arena, JPEG_EXACT, sizeof(JPEG_EXACT) / 2, RUBRAVIEW_JPEGTRAN_ROT_90,
            RUBRAVIEW_JPEGTRAN_TRIM, false);
        assert(cut.err == RUBRAVIEW_JPEGTRAN_OK || cut.err == RUBRAVIEW_JPEGTRAN_ERR_CORRUPT);

        /* Header cut off entirely. */
        rubraview_jpegtran_result_t tiny = rubraview_jpegtran_apply(
            &arena, JPEG_EXACT, 8, RUBRAVIEW_JPEGTRAN_ROT_90, RUBRAVIEW_JPEGTRAN_TRIM, false);
        assert(tiny.err != RUBRAVIEW_JPEGTRAN_OK);
    }
    printf("  [PASS] A corrupt or truncated file gives an error rather than taking the program down\n");

    free(raw);
    printf("[test_jpegtran] All tests passed successfully!\n");
    return 0;
}
