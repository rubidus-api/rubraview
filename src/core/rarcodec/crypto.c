static void sha256_block(uint32_t h[8], const uint8_t *b) {
    uint32_t w[64];
    for (int t = 0; t < 16; ++t) w[t] = load32be(b + 4 * t);
    for (int t = 16; t < 64; ++t) {
        uint32_t s0 = ror32(w[t - 15], 7) ^ ror32(w[t - 15], 18) ^ (w[t - 15] >> 3);
        uint32_t s1 = ror32(w[t - 2], 17) ^ ror32(w[t - 2], 19) ^ (w[t - 2] >> 10);
        w[t] = w[t - 16] + s0 + w[t - 7] + s1;
    }
    uint32_t a = h[0], bb = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
    for (int t = 0; t < 64; ++t) {
        uint32_t S1 = ror32(e, 6) ^ ror32(e, 11) ^ ror32(e, 25);
        uint32_t ch = (e & f) ^ (~e & g);
        uint32_t t1 = hh + S1 + ch + SHA256_K[t] + w[t];
        uint32_t S0 = ror32(a, 2) ^ ror32(a, 13) ^ ror32(a, 22);
        uint32_t maj = (a & bb) ^ (a & c) ^ (bb & c);
        uint32_t t2 = S0 + maj;
        hh = g; g = f; f = e; e = d + t1; d = c; c = bb; bb = a; a = t1 + t2;
    }
    h[0] += a; h[1] += bb; h[2] += c; h[3] += d; h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
}

void rc_sha256_init(rc_sha256_t *s) {
    static const uint32_t iv[8] = { 0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
                                    0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19 };
    memcpy(s->h, iv, sizeof(iv));
    s->length = 0;
    s->fill = 0;
}

void rc_sha256_update(rc_sha256_t *s, const void *data, size_t size) {
    const uint8_t *p = (const uint8_t*)data;
    s->length += size;
    while (size > 0) {
        if (s->fill == 0 && size >= 64) { sha256_block(s->h, p); p += 64; size -= 64; continue; }
        size_t n = 64 - s->fill;
        if (n > size) n = size;
        memcpy(s->block + s->fill, p, n);
        s->fill += n; p += n; size -= n;
        if (s->fill == 64) { sha256_block(s->h, s->block); s->fill = 0; }
    }
}

void rc_sha256_final(rc_sha256_t *s, uint8_t digest[32]) {
    uint64_t bits = s->length * 8;
    uint8_t pad = 0x80, zero = 0;
    rc_sha256_update(s, &pad, 1);
    while (s->fill != 56) rc_sha256_update(s, &zero, 1);
    uint8_t len[8];
    for (int i = 0; i < 8; ++i) len[i] = (uint8_t)(bits >> (56 - 8 * i));
    rc_sha256_update(s, len, 8);
    for (int i = 0; i < 8; ++i) store32be(digest + 4 * i, s->h[i]);
    rc_wipe(s, sizeof(*s));
}

void rc_sha256(const void *data, size_t size, uint8_t digest[32]) {
    rc_sha256_t s;
    rc_sha256_init(&s);
    rc_sha256_update(&s, data, size);
    rc_sha256_final(&s, digest);
}

/* ---- HMAC-SHA-256 (RFC 2104) and PBKDF2 (RFC 8018) ---- */

typedef struct hmac_ctx {
    rc_sha256_t inner, outer;   /* states after the padded key */
} hmac_ctx_t;

static void hmac_setup(hmac_ctx_t *c, const uint8_t *key, size_t key_len) {
    uint8_t k[64] = {0}, pad[64];
    if (key_len > 64) rc_sha256(key, key_len, k);
    else if (key_len > 0) memcpy(k, key, key_len);
    for (int i = 0; i < 64; ++i) pad[i] = k[i] ^ 0x36;
    rc_sha256_init(&c->inner);
    rc_sha256_update(&c->inner, pad, 64);
    for (int i = 0; i < 64; ++i) pad[i] = k[i] ^ 0x5c;
    rc_sha256_init(&c->outer);
    rc_sha256_update(&c->outer, pad, 64);
    rc_wipe(k, sizeof(k));
    rc_wipe(pad, sizeof(pad));
}

static void hmac_run(const hmac_ctx_t *c, const void *data, size_t size, uint8_t mac[32]) {
    rc_sha256_t s = c->inner;
    uint8_t inner[32];
    rc_sha256_update(&s, data, size);
    rc_sha256_final(&s, inner);
    s = c->outer;
    rc_sha256_update(&s, inner, 32);
    rc_sha256_final(&s, mac);
    rc_wipe(inner, sizeof(inner));
}

void rc_hmac_sha256(const uint8_t *key, size_t key_len, const void *data, size_t size, uint8_t mac[32]) {
    hmac_ctx_t c;
    hmac_setup(&c, key, key_len);
    hmac_run(&c, data, size, mac);
    rc_wipe(&c, sizeof(c));
}

/* Spec 6.2.1: one PBKDF2-HMAC-SHA-256 chain, read at 2^n, 2^n + 16 and 2^n + 32 iterations. */
bool rc_kdf50(const uint8_t *pwd8, size_t pwd8_len, const uint8_t salt[16], unsigned lg2_count,
              uint8_t key[32], uint8_t hash_key[32], uint8_t psw_check[8]) {
    if (lg2_count > 24) return false;
    hmac_ctx_t c;
    hmac_setup(&c, pwd8, pwd8_len);
    uint8_t msg[20], u[32], acc[32];
    memcpy(msg, salt, 16);
    msg[16] = 0; msg[17] = 0; msg[18] = 0; msg[19] = 1;
    hmac_run(&c, msg, 20, u);
    memcpy(acc, u, 32);
    uint64_t total = ((uint64_t)1 << lg2_count) + 32;
    for (uint64_t j = 2; j <= total; ++j) {
        if (j - 1 == ((uint64_t)1 << lg2_count)) memcpy(key, acc, 32);
        if (j - 1 == ((uint64_t)1 << lg2_count) + 16) memcpy(hash_key, acc, 32);
        hmac_run(&c, u, 32, u);
        for (int i = 0; i < 32; ++i) acc[i] ^= u[i];
    }
    uint8_t check[8] = {0};
    for (int j = 0; j < 32; ++j) check[j & 7] ^= acc[j];
    memcpy(psw_check, check, 8);
    rc_wipe(&c, sizeof(c)); rc_wipe(u, sizeof(u)); rc_wipe(acc, sizeof(acc));
    return true;
}

/* Spec 6.2.5: the HMAC of the CRC folded to 32 bits. */
uint32_t rc_crc_to_mac(uint32_t crc, const uint8_t hash_key[32]) {
    uint8_t raw[4], mac[32];
    store32le(raw, crc);
    rc_hmac_sha256(hash_key, 32, raw, 4, mac);
    uint8_t m[4] = { mac[0], mac[1], mac[2], mac[3] };
    for (int j = 4; j < 32; ++j) m[j & 3] ^= mac[j];
    return load32le(m);
}

/* Spec 6.1.1: RAR 3's SHA-1 key derivation, 2^18 rounds. */
void rc_kdf30(const uint8_t *pwd16, size_t pwd16_len, const uint8_t *salt, uint8_t key[16], uint8_t iv[16]) {
    uint8_t p[256 + 8];
    size_t plen = pwd16_len > 256 ? 256 : pwd16_len;
    memcpy(p, pwd16, plen);
    if (salt) { memcpy(p + plen, salt, 8); plen += 8; }
    rc_sha1_t s;
    rc_sha1_init(&s);
    for (uint32_t i = 0; i < 0x40000; ++i) {
        rc_sha1_update(&s, p, plen);
        uint8_t n[3] = { (uint8_t)i, (uint8_t)(i >> 8), (uint8_t)(i >> 16) };
        rc_sha1_update(&s, n, 3);
        if (i % 0x4000 == 0) {
            uint8_t d[20];
            rc_sha1_final(&s, d);
            iv[i / 0x4000] = d[19];
        }
    }
    uint8_t d[20];
    rc_sha1_final(&s, d);
    for (int g = 0; g < 4; ++g)
        for (int k = 0; k < 4; ++k) key[4 * g + k] = d[4 * g + 3 - k];
    rc_wipe(&s, sizeof(s)); rc_wipe(d, sizeof(d)); rc_wipe(p, sizeof(p));
}

