static void b2s_compress(rc_blake2s_t *s, const uint8_t block[64], bool last) {
    uint32_t m[16], v[16];
    for (int i = 0; i < 16; ++i) m[i] = load32le(block + 4 * i);
    for (int i = 0; i < 8; ++i) { v[i] = s->h[i]; v[i + 8] = B2S_IV[i]; }
    v[12] ^= s->t[0]; v[13] ^= s->t[1];
    if (last) { v[14] = ~v[14]; if (s->last_node) v[15] = ~v[15]; }
#define B2S_G(a, b, c, d, x, y)                         \
    do {                                                \
        v[a] = v[a] + v[b] + (x); v[d] = ror32(v[d] ^ v[a], 16); \
        v[c] = v[c] + v[d];       v[b] = ror32(v[b] ^ v[c], 12); \
        v[a] = v[a] + v[b] + (y); v[d] = ror32(v[d] ^ v[a], 8);  \
        v[c] = v[c] + v[d];       v[b] = ror32(v[b] ^ v[c], 7);  \
    } while (0)
    for (int r = 0; r < 10; ++r) {
        const uint8_t *z = B2S_SIGMA[r];
        B2S_G(0, 4, 8, 12, m[z[0]], m[z[1]]);
        B2S_G(1, 5, 9, 13, m[z[2]], m[z[3]]);
        B2S_G(2, 6, 10, 14, m[z[4]], m[z[5]]);
        B2S_G(3, 7, 11, 15, m[z[6]], m[z[7]]);
        B2S_G(0, 5, 10, 15, m[z[8]], m[z[9]]);
        B2S_G(1, 6, 11, 12, m[z[10]], m[z[11]]);
        B2S_G(2, 7, 8, 13, m[z[12]], m[z[13]]);
        B2S_G(3, 4, 9, 14, m[z[14]], m[z[15]]);
    }
#undef B2S_G
    for (int i = 0; i < 8; ++i) s->h[i] ^= v[i] ^ v[i + 8];
}

/* Parameter block of spec 5.3's table: digest 32, key 0, fanout 8, depth 2, node offset, node depth, inner 32. */
static void b2s_init_node(rc_blake2s_t *s, uint32_t node_offset, uint8_t node_depth, bool last_node) {
    uint8_t p[32] = {0};
    p[0] = 32; p[2] = 8; p[3] = 2;
    store32le(p + 8, node_offset);
    p[14] = node_depth; p[15] = 32;
    for (int i = 0; i < 8; ++i) s->h[i] = B2S_IV[i] ^ load32le(p + 4 * i);
    s->t[0] = s->t[1] = 0;
    s->fill = 0;
    s->last_node = last_node;
}

static void b2s_add_count(rc_blake2s_t *s, uint32_t n) {
    s->t[0] += n;
    if (s->t[0] < n) s->t[1]++;
}

static void b2s_update(rc_blake2s_t *s, const uint8_t *p, size_t size) {
    while (size > 0) {
        if (s->fill == 64) {   /* keep the last block back: it may be the final one */
            b2s_add_count(s, 64);
            b2s_compress(s, s->buf, false);
            s->fill = 0;
        }
        size_t n = 64 - s->fill;
        if (n > size) n = size;
        memcpy(s->buf + s->fill, p, n);
        s->fill += n; p += n; size -= n;
    }
}

static void b2s_final(rc_blake2s_t *s, uint8_t out[32]) {
    b2s_add_count(s, (uint32_t)s->fill);
    memset(s->buf + s->fill, 0, 64 - s->fill);
    b2s_compress(s, s->buf, true);
    for (int i = 0; i < 8; ++i) store32le(out + 4 * i, s->h[i]);
}

void rc_blake2sp_init(rc_blake2sp_t *s) {
    for (uint32_t i = 0; i < 8; ++i) b2s_init_node(&s->leaf[i], i, 0, i == 7);
    s->fill = 0;
}

/* Chunk k (64 bytes) goes to leaf k mod 8; a stripe of eight chunks is
   handed out once the next byte shows it is not the end. */
void rc_blake2sp_update(rc_blake2sp_t *s, const void *data, size_t size) {
    const uint8_t *p = (const uint8_t*)data;
    while (size > 0) {
        if (s->fill == 512) {
            for (int i = 0; i < 8; ++i) b2s_update(&s->leaf[i], s->buf + 64 * i, 64);
            s->fill = 0;
        }
        size_t n = 512 - s->fill;
        if (n > size) n = size;
        memcpy(s->buf + s->fill, p, n);
        s->fill += n; p += n; size -= n;
    }
}

void rc_blake2sp_final(rc_blake2sp_t *s, uint8_t digest[32]) {
    for (int i = 0; i < 8; ++i) {
        size_t at = 64 * (size_t)i;
        if (at < s->fill) b2s_update(&s->leaf[i], s->buf + at, s->fill - at < 64 ? s->fill - at : 64);
    }
    uint8_t leaves[256];
    for (int i = 0; i < 8; ++i) b2s_final(&s->leaf[i], leaves + 32 * i);
    rc_blake2s_t root;
    b2s_init_node(&root, 0, 1, true);
    b2s_update(&root, leaves, sizeof(leaves));
    b2s_final(&root, digest);
}
