/*
 * Rubraview's RAR codec (MIT): checksums, hashes and ciphers. Written from docs/specs/rar-decompression.md
 * (sections 5 and 6) and the standards it names: ISO 3309 CRC-32, FIPS 197 (AES; the tables below were
 * generated from FIPS 197's definitions), FIPS 180-4 (SHA-1, SHA-256), RFC 2104 (HMAC), RFC 8018 (PBKDF2),
 * RFC 7693 and the BLAKE2 paper (BLAKE2s, BLAKE2sp).
 */
#include "rc_internal.h"
#include <string.h>

void rc_wipe(void *p, size_t n) {
    volatile uint8_t *v = (volatile uint8_t*)p;
    while (n--) *v++ = 0;
}

static uint32_t load32le(const uint8_t *p) {
    return (uint32_t)p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
}
static uint32_t load32be(const uint8_t *p) {
    return (uint32_t)p[0] << 24 | (uint32_t)p[1] << 16 | (uint32_t)p[2] << 8 | (uint32_t)p[3];
}
static void store32be(uint8_t *p, uint32_t v) {
    p[0] = (uint8_t)(v >> 24); p[1] = (uint8_t)(v >> 16); p[2] = (uint8_t)(v >> 8); p[3] = (uint8_t)v;
}
static void store32le(uint8_t *p, uint32_t v) {
    p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24);
}
static uint32_t rol32(uint32_t x, unsigned n) { return (x << n) | (x >> (32 - n)); }
static uint32_t ror32(uint32_t x, unsigned n) { return (x >> n) | (x << (32 - n)); }

/* ---- CRC-32 (spec 5.1) ---- */

static uint32_t crc_table[8][256];
static bool crc_ready;

static void crc_init(void) {
    for (uint32_t i = 0; i < 256; ++i) {
        uint32_t c = i;
        for (int k = 0; k < 8; ++k) c = (c >> 1) ^ ((c & 1) ? 0xEDB88320u : 0);
        crc_table[0][i] = c;
    }
    for (uint32_t i = 0; i < 256; ++i)
        for (int t = 1; t < 8; ++t) crc_table[t][i] = (crc_table[t - 1][i] >> 8) ^ crc_table[0][crc_table[t - 1][i] & 0xFF];
    crc_ready = true;
}

uint32_t rc_crc32(uint32_t crc, const void *data, size_t size) {
    if (!crc_ready) crc_init();   /* the same values from any thread that races here */
    const uint8_t *p = (const uint8_t*)data;
    crc = ~crc;
    while (size >= 8) {
        uint32_t a = crc ^ load32le(p), b = load32le(p + 4);
        crc = crc_table[7][a & 0xFF] ^ crc_table[6][(a >> 8) & 0xFF] ^ crc_table[5][(a >> 16) & 0xFF] ^ crc_table[4][a >> 24] ^
              crc_table[3][b & 0xFF] ^ crc_table[2][(b >> 8) & 0xFF] ^ crc_table[1][(b >> 16) & 0xFF] ^ crc_table[0][b >> 24];
        p += 8; size -= 8;
    }
    while (size--) crc = (crc >> 8) ^ crc_table[0][(crc ^ *p++) & 0xFF];
    return ~crc;
}

/* ---- SHA-1 (FIPS 180-4, 6.1) ---- */

static void sha1_block(uint32_t h[5], const uint8_t *b) {
    uint32_t w[80];
    for (int t = 0; t < 16; ++t) w[t] = load32be(b + 4 * t);
    for (int t = 16; t < 80; ++t) w[t] = rol32(w[t - 3] ^ w[t - 8] ^ w[t - 14] ^ w[t - 16], 1);
    uint32_t a = h[0], bb = h[1], c = h[2], d = h[3], e = h[4];
    for (int t = 0; t < 80; ++t) {
        uint32_t f, k;
        if (t < 20) { f = (bb & c) ^ (~bb & d); k = 0x5A827999u; }
        else if (t < 40) { f = bb ^ c ^ d; k = 0x6ED9EBA1u; }
        else if (t < 60) { f = (bb & c) ^ (bb & d) ^ (c & d); k = 0x8F1BBCDCu; }
        else { f = bb ^ c ^ d; k = 0xCA62C1D6u; }
        uint32_t tmp = rol32(a, 5) + f + e + k + w[t];
        e = d; d = c; c = rol32(bb, 30); bb = a; a = tmp;
    }
    h[0] += a; h[1] += bb; h[2] += c; h[3] += d; h[4] += e;
}

void rc_sha1_init(rc_sha1_t *s) {
    static const uint32_t iv[5] = { 0x67452301u, 0xEFCDAB89u, 0x98BADCFEu, 0x10325476u, 0xC3D2E1F0u };
    memcpy(s->h, iv, sizeof(iv));
    s->length = 0;
    s->fill = 0;
}

void rc_sha1_update(rc_sha1_t *s, const void *data, size_t size) {
    const uint8_t *p = (const uint8_t*)data;
    s->length += size;
    while (size > 0) {
        if (s->fill == 0 && size >= 64) { sha1_block(s->h, p); p += 64; size -= 64; continue; }
        size_t n = 64 - s->fill;
        if (n > size) n = size;
        memcpy(s->block + s->fill, p, n);
        s->fill += n; p += n; size -= n;
        if (s->fill == 64) { sha1_block(s->h, s->block); s->fill = 0; }
    }
}

void rc_sha1_final(const rc_sha1_t *src, uint8_t digest[20]) {
    rc_sha1_t s = *src;
    uint64_t bits = s.length * 8;
    uint8_t pad = 0x80;
    rc_sha1_update(&s, &pad, 1);
    uint8_t zero = 0;
    while (s.fill != 56) rc_sha1_update(&s, &zero, 1);
    uint8_t len[8];
    for (int i = 0; i < 8; ++i) len[i] = (uint8_t)(bits >> (56 - 8 * i));
    rc_sha1_update(&s, len, 8);
    for (int i = 0; i < 5; ++i) store32be(digest + 4 * i, s.h[i]);
    rc_wipe(&s, sizeof(s));
}

