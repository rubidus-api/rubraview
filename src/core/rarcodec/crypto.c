static const uint8_t AES_RCON[11] = { 0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36 };

/* FIPS 197 5.2: the encryption key schedule, words as big-endian u32. */
static unsigned aes_expand(const uint8_t *key, unsigned key_bits, uint32_t w[60]) {
    unsigned nk = key_bits / 32, nr = nk + 6;
    for (unsigned i = 0; i < nk; ++i) w[i] = load32be(key + 4 * i);
    for (unsigned i = nk; i < 4 * (nr + 1); ++i) {
        uint32_t t = w[i - 1];
        if (i % nk == 0) {
            t = (t << 8) | (t >> 24);
            t = (uint32_t)AES_SBOX[t >> 24] << 24 | (uint32_t)AES_SBOX[(t >> 16) & 0xFF] << 16 |
                (uint32_t)AES_SBOX[(t >> 8) & 0xFF] << 8 | AES_SBOX[t & 0xFF];
            t ^= (uint32_t)AES_RCON[i / nk] << 24;
        } else if (nk > 6 && i % nk == 4) {
            t = (uint32_t)AES_SBOX[t >> 24] << 24 | (uint32_t)AES_SBOX[(t >> 16) & 0xFF] << 16 |
                (uint32_t)AES_SBOX[(t >> 8) & 0xFF] << 8 | AES_SBOX[t & 0xFF];
        }
        w[i] = w[i - nk] ^ t;
    }
    return nr;
}

static void add_round_key(uint8_t s[16], const uint32_t *w) {
    for (int c = 0; c < 4; ++c) {
        s[4 * c] ^= (uint8_t)(w[c] >> 24); s[4 * c + 1] ^= (uint8_t)(w[c] >> 16);
        s[4 * c + 2] ^= (uint8_t)(w[c] >> 8); s[4 * c + 3] ^= (uint8_t)w[c];
    }
}

static uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0)); }

/* FIPS 197 5.1, for the tests' known-answer vectors. */
void rc_aes_encrypt_block(const uint8_t *key, unsigned key_bits, const uint8_t in[16], uint8_t out[16]) {
    uint32_t w[60];
    unsigned nr = aes_expand(key, key_bits, w);
    uint8_t s[16], t[16];
    memcpy(s, in, 16);
    add_round_key(s, w);
    for (unsigned r = 1; r <= nr; ++r) {
        for (int i = 0; i < 16; ++i) s[i] = AES_SBOX[s[i]];
        for (int c = 0; c < 4; ++c)                       /* ShiftRows: row r moves left by r */
            for (int row = 0; row < 4; ++row) t[4 * c + row] = s[4 * ((c + row) & 3) + row];
        if (r != nr) {
            for (int c = 0; c < 4; ++c) {
                uint8_t a0 = t[4 * c], a1 = t[4 * c + 1], a2 = t[4 * c + 2], a3 = t[4 * c + 3], x = a0 ^ a1 ^ a2 ^ a3;
                s[4 * c] = a0 ^ x ^ xtime(a0 ^ a1);
                s[4 * c + 1] = a1 ^ x ^ xtime(a1 ^ a2);
                s[4 * c + 2] = a2 ^ x ^ xtime(a2 ^ a3);
                s[4 * c + 3] = a3 ^ x ^ xtime(a3 ^ a0);
            }
        } else memcpy(s, t, 16);
        add_round_key(s, w + 4 * r);
    }
    memcpy(out, s, 16);
    rc_wipe(w, sizeof(w));
}

bool rc_aes_init(rc_aes_t *a, const uint8_t *key, unsigned key_bits, const uint8_t iv[16]) {
    if (key_bits != 128 && key_bits != 256) return false;
    a->rounds = aes_expand(key, key_bits, a->rk);
    memcpy(a->iv, iv, 16);
    return true;
}

/* FIPS 197 5.3: the inverse cipher. */
static void aes_decrypt_block(const rc_aes_t *a, uint8_t s[16]) {
    unsigned nr = a->rounds;
    uint8_t t[16];
    add_round_key(s, a->rk + 4 * nr);
    for (unsigned r = nr; r-- > 0;) {
        for (int c = 0; c < 4; ++c)                       /* InvShiftRows: row r moves right by r */
            for (int row = 0; row < 4; ++row) t[4 * ((c + row) & 3) + row] = s[4 * c + row];
        for (int i = 0; i < 16; ++i) s[i] = AES_INV_SBOX[t[i]];
        add_round_key(s, a->rk + 4 * r);
        if (r != 0) {
            for (int c = 0; c < 4; ++c) {
                uint8_t a0 = s[4 * c], a1 = s[4 * c + 1], a2 = s[4 * c + 2], a3 = s[4 * c + 3];
                s[4 * c]     = AES_MUL14[a0] ^ AES_MUL11[a1] ^ AES_MUL13[a2] ^ AES_MUL9[a3];
                s[4 * c + 1] = AES_MUL9[a0] ^ AES_MUL14[a1] ^ AES_MUL11[a2] ^ AES_MUL13[a3];
                s[4 * c + 2] = AES_MUL13[a0] ^ AES_MUL9[a1] ^ AES_MUL14[a2] ^ AES_MUL11[a3];
                s[4 * c + 3] = AES_MUL11[a0] ^ AES_MUL13[a1] ^ AES_MUL9[a2] ^ AES_MUL14[a3];
            }
        }
    }
}

void rc_aes_cbc_decrypt(rc_aes_t *a, uint8_t *data, size_t size) {
    uint8_t c[16];
    for (size_t off = 0; off + 16 <= size; off += 16) {
        memcpy(c, data + off, 16);
        aes_decrypt_block(a, data + off);
        for (int i = 0; i < 16; ++i) data[off + i] ^= a->iv[i];
        memcpy(a->iv, c, 16);
    }
}

